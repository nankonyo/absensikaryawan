    public function run(): void
    {
        // Admin user (system administrator)
        $adminRole = Role::where('name', 'admin')->firstOrFail();

        User::updateOrCreate(
            ['email' => 'admin@example.com'],
            [
                'name' => 'Administrator Sistem',
                'role_id' => $adminRole->id,
                'employee_id' => 'EMP-000001',
                'phone' => '08120000001',
                'password' => Hash::make('password'),
                'email_verified_at' => now(),
            ]
        );

        // Employee data from current database
        $employees = $this->employeeData();

        // First pass: create all users
        $userMap = [];

        foreach ($employees as $emp) {
            $role = Role::where('name', $emp['role'])->firstOrFail();
            $department = $emp['department']
                ? Department::where('name', $emp['department'])->first()
                : null;
            $position = Position::where('name', $emp['jabatan'])->first();
            $unit = isset($emp['unit'])
                ? Unit::where('name', $emp['unit'])->first()
                : null;
            $branch = $emp['branch']
                ? Branch::where('name', $emp['branch'])->first()
                : null;

            $user = User::updateOrCreate(
                ['email' => $emp['email']],
                [
                    'name' => $emp['name'],
                    'role_id' => $role->id,
                    'employee_id' => $emp['employee_id'],
                    'phone' => $emp['phone'],
                    'birth_place' => $emp['birth_place'],
                    'birth_date' => $emp['birth_date'],
                    'gender' => $emp['gender'],
                    'position' => $emp['jabatan'],
                    'position_id' => $position?->id,
                    'department_id' => $department?->id,
                    'unit_id' => $unit?->id,
                    'branch_id' => $branch?->id,
                    'password' => Hash::make('password'),
                    'email_verified_at' => now(),
                ]
            );

            $userMap[$emp['employee_id']] = $user;

            $this->createAttributeValues($user, $emp);
        }

        // Second pass: set supervisor relationships
        foreach ($employees as $emp) {
            if ($emp['atasan'] !== null) {
                $user = $userMap[$emp['employee_id']] ?? null;
                $supervisor = $userMap[$emp['atasan']] ?? null;

                if ($user && $supervisor) {
                    $user->supervisor_id = $supervisor->id;
                    $user->save();
                }
            }
        }
    }

    private function createAttributeValues(User $user, array $emp): void
    {
        $attributes = [
            'join_date' => $emp['join_date'] ?? null,
            'resign_date' => $emp['resign_date'] ?? null,
            'address' => $emp['address'] ?? null,
            'npwp' => $emp['npwp'] ?? null,
            'bank_name' => $emp['bank_name'] ?? null,
            'bank_account' => $emp['bank_account'] ?? null,
            'bank_account_holder' => $emp['bank_account_holder'] ?? null,
            'bpjs_ketenagakerjaan' => $emp['bpjs_ketenagakerjaan'] ?? null,
            'bpjs_kesehatan' => $emp['bpjs_kesehatan'] ?? null,
            'religion' => $emp['religion'] ?? null,
            'marital_status' => $emp['marital_status'] ?? null,
            'blood_type' => $emp['blood_type'] ?? null,
        ];

        foreach ($attributes as $name => $value) {
            if ($value === null) {
                continue;
            }

            $attr = UserAttribute::where('name', $name)->first();
            if ($attr) {
                UserAttributeValue::updateOrCreate(
                    ['user_id' => $user->id, 'user_attribute_id' => $attr->id],
                    ['value' => $value]
                );
            }
        }
    }

